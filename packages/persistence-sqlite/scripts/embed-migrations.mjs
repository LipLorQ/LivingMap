// Embeds drizzle-kit generated SQL into a TS module so migrations ship inside the
// bundled Electron main process without runtime filesystem path resolution (ADR-0003).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const journal = JSON.parse(readFileSync(join(root, "drizzle/meta/_journal.json"), "utf8"));

const migrations = journal.entries
  .sort((a, b) => a.idx - b.idx)
  .map(({ tag }) => ({
    tag,
    statements: readFileSync(join(root, "drizzle", `${tag}.sql`), "utf8")
      .split("--> statement-breakpoint")
      .map((s) => s.trim())
      .filter(Boolean),
  }));

writeFileSync(
  join(root, "src/migrations.generated.ts"),
  `// GENERATED by scripts/embed-migrations.mjs from ./drizzle — do not edit.\n` +
    `export const MIGRATIONS: ReadonlyArray<{ tag: string; statements: readonly string[] }> = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`Embedded ${migrations.length} migration(s).`);
